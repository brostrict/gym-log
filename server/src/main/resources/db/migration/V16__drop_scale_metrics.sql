-- ============================================================
-- V16 —— 去掉体脂秤推算的五项，改为「从自测数据推导」
--
-- 删掉：BODY_FAT / MUSCLE_MASS / WATER_PCT / BMR / VISCERAL_FAT
--
-- 【为什么删】
--
-- 这五项不是「测」出来的，是体脂秤用生物电阻抗 + 公式**推算**的：
--
--   · 不同品牌算法差异极大，同一人在两台秤上能差 3–5 个百分点
--     （V15 里 M6-B-6 的注释自己就写了这一条）
--   · 用户无法独立验证 —— 你不知道秤上的 18.7% 到底对不对
--   · 趋势没有行动含义 —— BMR 从 1625 掉到 1605，你能做什么？什么都做不了。
--     而腰围从 86 掉到 81.6 是明确的行为反馈
--
-- 一条判据就够：**用户能不能自己测**。
-- 体重（秤）、围度（软尺）、静息心率（数脉搏）、主观感受 —— 都能。
-- 这五项都不能。
--
-- 【改成什么】
--
-- 其中真正有意义的部分**从自测数据推导**，而且推导过程是**公开的公式**，
-- 不是某个厂商的黑箱：
--
--   BMI     = 体重 / 身高²
--   体脂率  = Deurenberg 公式（由 BMI + 年龄 + 性别推）
--   BMR     = Mifflin-St Jeor 公式（由体重 + 身高 + 年龄 + 性别推）
--
-- 它们仍然不准（体脂率估算误差 ±5%），但**误差是可知的、一致的**，
-- 而且换设备不会跳变。见后续迁移里的 user_profile。
--
-- 【⚠️ 这个迁移会删数据】
--
-- 删掉库里所有这五项的记录，**不可恢复**。
-- 理由：枚举值一旦从 BodyMetricType 里去掉，这些行就再也映射不回来
-- （MyBatis 按 name() 反序列化，找不到枚举会直接抛异常）——
-- 也就是说它们会变成「读不出来的行」，任何 selectList 都会炸。
--
-- 留着「读不出来的行」比删掉危险得多：删掉是显式的、立刻可见的，
-- 而读不出来的行会在某个不相干的查询里突然抛异常。
-- ============================================================


-- ------------------------------------------------------------
-- 一、删数据
-- ------------------------------------------------------------
--
-- ⚠️ 后面跟一条断言（见文件末尾）——「影响 0 行」在 Flyway 里是**合法成功**，
-- 静默失效必须变成硬失败（这条教训记在 DEV-LOG 踩坑 43）。

DELETE FROM `body_metric`
WHERE `metric_type` IN ('BODY_FAT', 'MUSCLE_MASS', 'WATER_PCT', 'BMR', 'VISCERAL_FAT');


-- ------------------------------------------------------------
-- 二、删 device 列
-- ------------------------------------------------------------
--
-- device（体脂秤型号，M6-B-6）只服务这五项：它的全部意义是
-- 「换秤时在图上标注断点，免得把算法差异当成身体变化」。
-- 五项没了，它就没有对象了。
--
-- 留着一个永远为 NULL 的列，就是这个项目一直在清理的那种东西
-- （见「零调用者的 countsTowardVolume」）。删掉。
--
-- ⚠️ DROP COLUMN 不可逆。回滚要重建列 + 重新录数据。

ALTER TABLE `body_metric` DROP COLUMN `device`;


-- ------------------------------------------------------------
-- 三、断言：五项真的没了
-- ------------------------------------------------------------
--
-- 「影响 0 行」是合法成功——如果 DELETE 因为拼写错误一条都没删，
-- Flyway 照样报通过，而库里留着一堆读不出来的行。
-- 所以这里跟一条**会失败的查询**，让静默失效变成硬失败。

SELECT IF(
    (SELECT COUNT(*) FROM `body_metric`
     WHERE `metric_type` IN ('BODY_FAT', 'MUSCLE_MASS', 'WATER_PCT', 'BMR', 'VISCERAL_FAT')) = 0,
    1,
    (SELECT 1 UNION ALL SELECT 2)
) AS `v16_assert_scale_metrics_gone`;
