-- ============================================================
-- V13 —— 修正 duration_sec 的列注释
--
-- 【为什么单独一个迁移改注释】
--
-- V11 里这个列的注释写的是：
--
--   「训练时长由客户端记录后上报，**不在这里算 (finished_at - started_at)**。
--     因为用户可能中途暂停（接电话、等器械），
--     墙上时间不等于实际训练时间，而暂停时长只有客户端知道。」
--
-- 那句话描述的是一个**当时并未实现的设计**。客户端确实上报了，
-- 但上报的恰恰就是墙上时间——没有任何暂停扣除。
-- **注释和实现对不上。**
--
-- 步骤 3.7 改成从组记录推算之后，注释终于需要更新了。
--
-- 【⚠️ 但不能直接改 V11】
--
-- Flyway 会校验已应用迁移的 checksum，改一个字符启动就会失败。
-- 迁移文件是**只追加的历史记录**，不是「当前状态的描述」。
--
-- 所以只能在新的迁移里改。
--
-- （同样的处理方式在 V11 头部也用过一次——那里说明了 V7 里
--   program.version 的注释已经过期。）
-- ============================================================

ALTER TABLE `workout_session`
    MODIFY COLUMN `duration_sec` INT NULL
        COMMENT '训练时长（秒）= 最后一组的完成时刻 − started_at。不是「点结束的时刻」，见 SessionService.resolveDuration';
