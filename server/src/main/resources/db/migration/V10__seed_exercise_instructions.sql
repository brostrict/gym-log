-- ============================================================
-- V10 —— 补充动作要领与常见错误
--
-- 【为什么只补 41 个，不是全部 90 个】
--
-- 这 41 个是 6 个内置计划模板引用到的**全部**动作（去重后）。
-- 其余 49 个是冷门变式（各种握距、角度、器械的细分），
-- 补它们的边际收益很低——用户自己挑动作时几乎不会翻到，
-- 而模板是「零配置开始训练」的入口，必定会看到。
--
-- 如果将来发现某个动作缺内容，按同样的格式追加即可。
--
-- 【格式约定】
--   动作要领：起始姿势 → 动作过程 → 关键提示，2–4 句
--   常见错误：2–3 条，每条附「为什么错」或「怎么改」，不是干巴巴的「别这样」
--
-- 【⚠️ WHERE 必须限定 user_id = 0】
-- 内置动作的 user_id 是 0（哨兵值，见 V4 注释）。
-- 不限定的话，如果某个用户恰好建了一个同名的自定义动作，
-- 这条 UPDATE 会把内容写到**他的**动作上。
-- 唯一索引是 (user_id, name)，同名不同用户是完全合法的。
-- ============================================================


