-- ============================================================
-- V6 —— 修正动作库的别名与分类
--
-- 这些问题是**实际测试接口时发现的**，不是设计时能想到的：
--
--   ① 用户搜「徒手」得到 0 条结果——数据里写的是「自重」，
--      而用户的说法是「徒手」。术语和用户认知不一致。
--
--   ②「动感单车」被归到了 SQUAT 动作模式——骑车不是蹲。
--      这是写种子数据时批量赋值导致的。
--
-- ⚠️ 为什么不直接改 V5：
--    V5 已经执行过了，Flyway 校验 checksum，改动会导致启动失败。
--    **已执行的迁移脚本是不可变的**——这正是版本化迁移的约束，
--    也是它可靠的原因。修正走新建脚本。
-- ============================================================

-- ---------- ① 给自重动作补上「徒手」「无器械」等用户常用说法 ----------
--
-- 用 CONCAT 追加而不是覆盖，保留原有的英文别名。
-- 用 FIND_IN_SET 判断避免重复添加（幂等）。
UPDATE `exercise`
SET `alias` = CONCAT(`alias`, ',徒手,无器械')
WHERE `user_id` = 0
  AND `equipment` = 'BODYWEIGHT'
  AND `alias` IS NOT NULL
  AND NOT FIND_IN_SET('徒手', `alias`);

-- 没有别名的自重动作，直接设置
UPDATE `exercise`
SET `alias` = '徒手,无器械'
WHERE `user_id` = 0
  AND `equipment` = 'BODYWEIGHT'
  AND `alias` IS NULL;

-- ---------- ② 修正动感单车的分类 ----------
--
-- 骑车时腿部动作接近伸膝，但整体不是蹲的模式——
-- 没有髋膝同时屈伸的负重过程。归到「无特定模式」比归错更好。
UPDATE `exercise`
SET `movement_pattern` = NULL
WHERE `user_id` = 0
  AND `name` = '动感单车';

-- ---------- ③ 椭圆机同理 ----------
-- （它在 V5 里已经是 NULL，这里只是显式确认，防止将来被误改）
-- 无操作。

-- ============================================================
-- 验证
-- ============================================================
SELECT '自重动作别名已更新' AS `说明`, COUNT(*) AS `数量`
FROM `exercise`
WHERE `user_id` = 0
  AND `equipment` = 'BODYWEIGHT'
  AND `alias` LIKE '%徒手%';
