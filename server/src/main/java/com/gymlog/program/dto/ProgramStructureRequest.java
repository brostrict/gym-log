package com.gymlog.program.dto;

import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;

import java.util.List;

/**
 * 编辑计划结构的请求 —— 提交**完整的**周与训练日，服务端全量替换。
 *
 * <h3>为什么是全量替换，而不是「加一个动作」「删一个训练日」这种细粒度接口</h3>
 *
 * <p>三个理由，按重要性排序：
 *
 * <ol>
 *   <li><b>客户端本来就是这样编辑的。</b>
 *       用户在计划编辑页面对着一个表单改，点保存时手里就是完整结构。
 *       细粒度接口会逼客户端自己算「我改了哪些」——而这个 diff 逻辑
 *       要在 Flutter 和 Vue 里各写一遍，且容易和校验规则不一致。</li>
 *
 *   <li><b>校验规则能整体复用。</b>
 *       超级组至少两个动作、组内顺序不重复、逐组序号不重复——
 *       这些都是**跨记录**约束。细粒度接口每次只看到一个动作，
 *       根本没法定这些规则。全量替换下直接复用创建时的那套校验。</li>
 *   <li><b>没有中间状态。</b>
 *       细粒度接口意味着「删了旧动作、还没加新动作」的瞬间对外可见，
 *       此时的数据是**不合法的**（超级组只剩一个成员）。
 *       全量替换在一个事务里完成，从外面看只有改前和改后两个状态。</li>
 * </ol>
 *
 * <p><b>代价</b>：所有子记录的 id 每次编辑都会变。
 * 这是可以接受的，因为**会话快照存的是值不是外键**——
 * 详见 REQUIREMENTS 6.3 不变量 2 的实现约束。
 * 如果哪天改成会话引用结构表，这个接口就必须推倒重来。
 *
 * <h3>为什么复用 {@link ProgramCreateRequest} 的嵌套 record</h3>
 *
 * <p>「创建一个计划需要什么形状」和「编辑一个计划的结构需要什么形状」
 * <b>是同一个形状</b>。重复定义一份的话，
 * 两边的校验注解（`@Min` / `@Max` / `@DecimalMax`）就有了分叉的余地——
 * 而分叉之后，创建时允许的值编辑时可能被拒，反之亦然，
 * 排查起来非常费劲。
 *
 * <p>所以这里**不重新定义**，直接引用。创建请求里多出来的
 * {@code name} / {@code description} / {@code totalWeeks} / {@code startDate}
 * 属于「元信息」，由 {@code PUT /programs/{id}} 单独管——
 * 改个名字不该导致上百条子记录被删了重建。
 */
public record ProgramStructureRequest(

        /** 周结构。传空列表 = 删掉所有周期化配置 */
        @Valid
        List<ProgramCreateRequest.WeekRequest> weeks,

        /** 训练日。传空列表 = 该计划没有任何训练日 */
        @Valid
        List<ProgramCreateRequest.DayRequest> days,

        /**
         * 客户端读取到的版本号，用于**乐观锁**。
         *
         * <p><b>为什么是必填而不是可选</b>：
         * 可选的并发检查等于默认关闭的并发检查，而它要防的
         * 恰恰是**静默的数据丢失**：
         *
         * <pre>
         *   手机和电脑同时打开计划编辑页
         *   手机加了深蹲 → 保存
         *   电脑加了卧推 → 保存        ← 手机加的深蹲被整个覆盖掉了
         * </pre>
         *
         * <p>全量替换下，后保存的一方会把另一方的改动**整份抹掉**，
         * 而且两边都不会收到任何提示。
         *
         * <p>必填还带来一个额外好处：客户端**必须先读过计划**才能提交，
         * 不可能提交一份自己都没见过的结构。
         */
        @NotNull(message = "缺少版本号，请先读取计划的最新状态")
        Integer expectedVersion

) {
}
