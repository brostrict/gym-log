package com.gymlog.exercise;

import lombok.Getter;

/**
 * 动作模式 —— 按「身体怎么动」分类，与器械和肌群都正交。
 *
 * <p><b>这个分类的实用价值：找替代动作</b>。
 *
 * <p>当深蹲架被占了，用户需要一个替代动作。按肌群找会推荐出
 * 「腿举」这种固定器械动作，但按动作模式找会推荐「高脚杯深蹲」
 * 「箭步蹲」——**同样的运动模式，训练效果更接近**。
 *
 * <p>运动科学上，动作模式是比肌群更本质的分类：
 * 它决定了关节角度、发力顺序和神经适应。
 */
@Getter
public enum MovementPattern {

    /** 水平推：卧推、俯卧撑 */
    HORIZONTAL_PUSH("水平推"),

    /** 水平拉：划船、反向飞鸟 */
    HORIZONTAL_PULL("水平拉"),

    /** 垂直推：推举、倒立撑 */
    VERTICAL_PUSH("垂直推"),

    /** 垂直拉：引体向上、高位下拉 */
    VERTICAL_PULL("垂直拉"),

    /** 蹲：深蹲、腿举、箭步蹲 */
    SQUAT("蹲"),

    /** 髋铰链：硬拉、臀桥、罗马尼亚硬拉 */
    HINGE("髋铰链"),

    /** 弓步：保加利亚分腿蹲、行走箭步蹲 */
    LUNGE("弓步"),

    /** 核心：平板支撑、卷腹、死虫 */
    CORE("核心"),

    /** 负重行走：农夫行走、手提箱行走 */
    CARRY("负重行走"),

    // ---------- 以下三类是写种子数据时补上的 ----------
    //
    // 最初只定义了上面 9 个大肌群复合动作的模式，写到手臂和腿部时发现
    // 弯举、臂屈伸、提踵这三类动作无处归类。
    //
    // 这说明一个常见问题：**分类维度是从「典型场景」想出来的，
    // 但真实数据总有例外**。好在这里补的成本很低——
    // 枚举加常量 + 数据库不需要改（VARCHAR 存的是名字，不是序号）。

    /** 肘屈（弯举类）：杠铃弯举、锤式弯举 */
    ELBOW_FLEXION("肘屈"),

    /** 肘伸（臂屈伸类）：绳索下压、仰卧臂屈伸 */
    ELBOW_EXTENSION("肘伸"),

    /** 踝跖屈（提踵类）：站姿提踵、坐姿提踵 */
    CALF_RAISE("提踵");

    private final String displayName;

    MovementPattern(String displayName) {
        this.displayName = displayName;
    }
}
